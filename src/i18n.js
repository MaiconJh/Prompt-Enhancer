let currentLang = 'en';

function resolveAuto() {
  try {
    const nav = (typeof navigator !== 'undefined' && navigator.language) ? navigator.language : 'en';
    if (nav && nav.toLowerCase().startsWith('pt')) return 'pt-BR';
    return 'en';
  } catch (e) {
    return 'pt-BR';
  }
}

function normalize(lang) {
  if (lang === 'auto') return resolveAuto();
  if (lang === 'en') return 'en';
  return 'pt-BR';
}

function initLanguage() {
  try {
    const stored = (typeof GM_getValue === 'function') ? GM_getValue(I18N_STORAGE_KEY, 'auto') : 'auto';
    currentLang = normalize(stored);
  } catch (e) {
    currentLang = resolveAuto();
  }
}

function t(key, params) {
  const dict = DICTS[currentLang] || DICTS['pt-BR'];
  let str = (dict && dict[key] != null) ? dict[key] : (DICTS['pt-BR'][key] != null ? DICTS['pt-BR'][key] : key);
  if (typeof str !== 'string') str = String(str == null ? key : str);
  if (params && typeof params === 'object') {
    for (const k of Object.keys(params)) {
      const esc = k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      const reBrace = new RegExp('\\{\\{' + esc + '\\}\\}', 'g');
      const rePlain = new RegExp('\\{' + esc + '\\}', 'g');
      const v = String(params[k]);
      str = str.replace(reBrace, () => v).replace(rePlain, () => v);
    }
  }
  return str;
}

function tPlural(key, n, forms) {
  forms = forms || {};
  const form = n === 1 ? (forms.one || '') : (forms.other || '');
  return form || t(key, Object.assign({}, forms, { n: n }));
}

function formatDate(ts) {
  try {
    const d = (ts instanceof Date) ? ts : new Date(ts);
    const locale = currentLang === 'en' ? 'en-US' : 'pt-BR';
    return d.toLocaleString(locale);
  } catch (e) {
    return String(ts);
  }
}

function formatBytes(n) {
  if (typeof Utils !== 'undefined' && typeof Utils.formatBytes === 'function') {
    return Utils.formatBytes(n);
  }
  const units = ['B', 'KB', 'MB', 'GB'];
  let i = 0; let v = n;
  while (v >= 1024 && i < units.length - 1) { v /= 1024; i++; }
  return `${v.toFixed(v < 10 && i > 0 ? 1 : 0)} ${units[i]}`;
}

function setLanguage(lang) {
  const next = normalize(lang === 'auto' ? 'auto' : lang);
  try {
    if (typeof GM_setValue === 'function') GM_setValue(I18N_STORAGE_KEY, lang);
  } catch (e) {}
  currentLang = next;
  try {
    if (typeof window !== 'undefined' && typeof window.dispatchEvent === 'function') {
      window.dispatchEvent(new CustomEvent('pe:i18n-changed', { detail: { lang: currentLang } }));
    }
  } catch (e) {}
}

function getLanguage() { return currentLang; }
function getStoredLanguage() {
  try {
    return (typeof GM_getValue === 'function') ? GM_getValue(I18N_STORAGE_KEY, 'auto') : 'auto';
  } catch (e) { return 'auto'; }
}

